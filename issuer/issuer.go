// Package issuer erzeugt Schlüsselpaare und signiert Lizenzschlüssel.
// Es gehört auf die Herstellerseite und wird von der lizenzierten Anwendung
// nicht importiert.
package issuer

import (
	"bytes"
	"crypto/ed25519"
	"crypto/rand"
	"crypto/x509"
	"encoding/base64"
	"encoding/pem"
	"errors"
	"fmt"
	"go/format"
	"time"

	license "github.com/h2-invent/go-license"
)

// GenerateKey erzeugt ein neues Ed25519-Schlüsselpaar.
func GenerateKey() (ed25519.PublicKey, ed25519.PrivateKey, error) {
	return ed25519.GenerateKey(rand.Reader)
}

// EncodePrivateKey liefert den privaten Schlüssel als PEM (PKCS#8, mit
// OpenSSL kompatibel).
func EncodePrivateKey(priv ed25519.PrivateKey) ([]byte, error) {
	der, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}), nil
}

// EncodePublicKey liefert den öffentlichen Schlüssel als PEM (PKIX).
func EncodePublicKey(pub ed25519.PublicKey) ([]byte, error) {
	der, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der}), nil
}

// ParsePrivateKey liest einen PEM-kodierten Ed25519-Schlüssel.
func ParsePrivateKey(data []byte) (ed25519.PrivateKey, error) {
	b, _ := pem.Decode(data)
	if b == nil || b.Type != "PRIVATE KEY" {
		return nil, errors.New("kein PEM-Block \"PRIVATE KEY\"")
	}
	k, err := x509.ParsePKCS8PrivateKey(b.Bytes)
	if err != nil {
		return nil, err
	}
	priv, ok := k.(ed25519.PrivateKey)
	if !ok {
		return nil, fmt.Errorf("kein Ed25519-Schlüssel, sondern %T", k)
	}
	return priv, nil
}

// ParsePublicKey liest einen PEM-kodierten öffentlichen Ed25519-Schlüssel.
func ParsePublicKey(data []byte) (ed25519.PublicKey, error) {
	b, _ := pem.Decode(data)
	if b == nil || b.Type != "PUBLIC KEY" {
		return nil, errors.New("kein PEM-Block \"PUBLIC KEY\"")
	}
	k, err := x509.ParsePKIXPublicKey(b.Bytes)
	if err != nil {
		return nil, err
	}
	pub, ok := k.(ed25519.PublicKey)
	if !ok {
		return nil, fmt.Errorf("kein Ed25519-Schlüssel, sondern %T", k)
	}
	return pub, nil
}

// Sign signiert eine Lizenz und liefert den Lizenzschlüssel.
// Fehlt IssuedAt, wird die aktuelle Zeit verwendet.
func Sign(priv ed25519.PrivateKey, l license.License) (string, error) {
	if len(priv) != ed25519.PrivateKeySize {
		return "", errors.New("ungültiger privater Schlüssel")
	}
	if l.IssuedAt.IsZero() {
		l.IssuedAt = time.Now()
	}
	p, err := license.MarshalPayload(l)
	if err != nil {
		return "", err
	}
	enc := base64.RawURLEncoding.EncodeToString(p)
	sig := ed25519.Sign(priv, license.SigningInput(enc))
	return license.Prefix + "." + enc + "." + base64.RawURLEncoding.EncodeToString(sig), nil
}

// NewID liefert eine zufällige Lizenz-ID (16 Zeichen, base32-ähnlich).
func NewID() string {
	const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
	b := make([]byte, 16)
	_, _ = rand.Read(b)
	for i := range b {
		b[i] = alphabet[int(b[i])%len(alphabet)]
	}
	return string(b)
}

// GoSource erzeugt eine Go-Datei, die den öffentlichen Schlüssel maskiert
// einbettet (zwei XOR-Hälften mit Zufallsmaske) und eine Funktion funcName()
// ed25519.PublicKey bereitstellt.
func GoSource(pkg, funcName string, pub ed25519.PublicKey) ([]byte, error) {
	if len(pub) != ed25519.PublicKeySize {
		return nil, errors.New("ungültiger öffentlicher Schlüssel")
	}
	mask := make([]byte, ed25519.PublicKeySize)
	if _, err := rand.Read(mask); err != nil {
		return nil, err
	}
	masked := make([]byte, ed25519.PublicKeySize)
	for i := range masked {
		masked[i] = pub[i] ^ mask[i]
	}
	lit := func(b []byte) string {
		var buf bytes.Buffer
		for i, c := range b {
			if i%8 == 0 {
				buf.WriteString("\n\t")
			}
			fmt.Fprintf(&buf, "0x%02x, ", c)
		}
		buf.WriteString("\n")
		return buf.String()
	}
	src := fmt.Sprintf(`// Code generated by licensectl gocode; DO NOT EDIT.
// Öffentlicher Lizenzschlüssel, Fingerprint %s.

package %s

import (
	"crypto/ed25519"

	license "github.com/h2-invent/go-license"
)

// %s liefert den einkompilierten öffentlichen Schlüssel für die Lizenzprüfung.
func %s() ed25519.PublicKey {
	a := [32]byte{%s}
	b := [32]byte{%s}
	return license.UnmaskKey(a[:], b[:])
}
`, license.Fingerprint(pub), pkg, funcName, funcName, lit(masked), lit(mask))
	return format.Source([]byte(src))
}
